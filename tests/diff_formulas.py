def formulas():
    out = []
    for line in F.strip().splitlines():
        out += [x for x in line.split("|") if x]
    return out


def load(d):
    spec = importlib.util.spec_from_file_location("folio_sheets_core", d + "/folio_sheets_core.so")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def book(m, blank):
    b = m.Book.open(blank)
    for r, row in enumerate(DATA):
        for c, v in enumerate(row):
            b.set_input(0, r, c, str(v))
    b.set_input(0, 19, 0, "=SUM(B2:B3)")
    return b


def norm(v):
    if isinstance(v, float):
        if v == 0:
            return 0.0
        return float("%.9g" % v)
    return v


def same(a, b):
    if isinstance(a, float) and isinstance(b, float):
        return a == b or abs(a - b) <= 1e-7 * max(abs(a), abs(b), 1e-300)
    return a == b


def main():
    old, new = load(sys.argv[1]), load(sys.argv[2])
    blank = sys.argv[3] if len(sys.argv) > 3 else "/tmp/old/Blank.xlsx"
    bo, bn = book(old, blank), book(new, blank)
    fs = formulas()
    bad = 0
    for i, f in enumerate(fs):
        r, c = 30 + i, 8
        for b in (bo, bn):
            try:
                b.set_input(0, r, c, "=" + f)
            except Exception as e:
                pass
        vo, vn = norm(bo.value(0, r, c)), norm(bn.value(0, r, c))
        do, dn = bo.display(0, r, c), bn.display(0, r, c)
        if not same(vo, vn) or (do != dn and not isinstance(vo, float)):
            bad += 1
            print("%-60s old=%r new=%r   [%s | %s]" % (f[:60], vo, vn, do, dn))
    print("%d formulas, %d differ" % (len(fs), bad))


main()
